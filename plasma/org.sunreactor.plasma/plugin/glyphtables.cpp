const QHash<char32_t, quint8> &segFace()
{
    static const QHash<char32_t, quint8> face = [] {
        QHash<char32_t, quint8> f;
        for (const SegSource &s : kSeg) {
            f.insert(s.code, s.bits);
        }
        return f;
    }();
    return face;
}

bool isSegNarrow(char32_t c)
{
    return c == U':' || c == U'.';
}

