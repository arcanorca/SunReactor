Face buildFace(const GlyphSource *begin, const GlyphSource *end)
{
    Face face;
    for (const GlyphSource *g = begin; g != end; ++g) {
        Glyph glyph;
        const QByteArrayView all(g->rows);
        int y = 0;
        qsizetype from = 0;
        while (from <= all.size() && y < 9) {
            qsizetype bar = all.indexOf('|', from);
            if (bar < 0) {
                bar = all.size();
            }
            const QByteArrayView row = all.sliced(from, bar - from);
            glyph.width = std::max<int>(glyph.width, static_cast<int>(row.size()));
            quint8 bits = 0;
            for (qsizetype x = 0; x < row.size(); ++x) {
                if (row.at(x) == '#') {
                    bits |= quint8(1u << (row.size() - 1 - x));
                }
            }
            glyph.bits[static_cast<size_t>(y)] = bits;
            ++y;
            from = bar + 1;
        }
        glyph.rows = y;
        face.insert(g->code, glyph);
    }
    return face;
}

